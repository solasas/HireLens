"""Generates an explainable evaluation of a candidate against a job.

The numeric score, fit_level, and missing_required_skills are never
generated by the LLM — they come directly from the deterministic
matching engine (app.domain.scoring.MatchResult), exactly like
duration_months in resume extraction and the overall_score design from
the start of this project: the model reasons in prose, it doesn't invent
numbers that are already known exactly.
"""

import json
import logging

from app.domain.scoring import MatchResult
from app.schemas.evaluation import CandidateEvaluation, CandidateEvaluationNarrative, FitLevel
from app.schemas.job_extraction import JobExtraction
from app.schemas.resume_extraction import ResumeExtraction
from app.services.llm.base import LLMProvider
from app.services.llm.extraction import extract_with_retry
from app.services.llm.prompts.candidate_evaluation import (
    SYSTEM_INSTRUCTIONS,
    build_candidate_evaluation_prompt,
)

logger = logging.getLogger(__name__)

# Mirrors the 1-10 mapping from the original scoring design doc:
# final_score is 0-1 from the matching engine, mapped onto the 1-10
# scale the product surfaces to a reviewer.
_SCORE_MIN = 1.0
_SCORE_SPAN = 9.0

STRONG_FIT_THRESHOLD = 7.5
MODERATE_FIT_THRESHOLD = 5.0

_REDACTED_CANDIDATE_FIELDS = ("name", "email", "phone", "location")


def _score_from_match(match: MatchResult) -> float:
    return round(_SCORE_MIN + match.final_score * _SCORE_SPAN, 1)


def _fit_level_from_score(score: float) -> FitLevel:
    if score >= STRONG_FIT_THRESHOLD:
        return FitLevel.STRONG_FIT
    if score >= MODERATE_FIT_THRESHOLD:
        return FitLevel.MODERATE_FIT
    return FitLevel.WEAK_FIT


def _redact_candidate(candidate: ResumeExtraction) -> dict:
    """Strips identity-adjacent fields before anything is sent to the
    LLM. Structural enforcement of rule 5 (no decisions based on name,
    etc.) rather than relying on the model to honor a prompt instruction
    it can't verify itself — and a PII-minimization side benefit: no
    reason to hand a third-party API more personal data than the task
    needs."""
    data = candidate.model_dump()
    for field in _REDACTED_CANDIDATE_FIELDS:
        data.pop(field, None)
    return data


def _matching_results_dict(match: MatchResult) -> dict:
    return {
        "skill_score": match.skill_score,
        "experience_score": match.experience_score,
        "education_score": match.education_score,
        "semantic_score": match.semantic_score,
        "project_score": match.project_score,
        "final_score": match.final_score,
        "matched_skills": match.matched_skills,
        "missing_required_skills": match.missing_required_skills,
        "matched_preferred_skills": match.matched_preferred_skills,
    }


async def evaluate_candidate(
    candidate: ResumeExtraction,
    job: JobExtraction,
    match: MatchResult,
    *,
    llm: LLMProvider,
) -> CandidateEvaluation:
    prompt = build_candidate_evaluation_prompt(
        candidate_json=json.dumps(_redact_candidate(candidate)),
        job_json=job.model_dump_json(),
        matching_results_json=json.dumps(_matching_results_dict(match)),
    )

    narrative = await extract_with_retry(
        llm,
        system_instruction=SYSTEM_INSTRUCTIONS,
        prompt=prompt,
        schema=CandidateEvaluationNarrative,
    )

    score = _score_from_match(match)
    return CandidateEvaluation(
        score=score,
        fit_level=_fit_level_from_score(score),
        strengths=narrative.strengths,
        missing_required_skills=match.missing_required_skills,
        relevant_experience=narrative.relevant_experience,
        concerns=narrative.concerns,
        recommendation=narrative.recommendation,
    )
